/// Centralized spacing scale. Use these instead of arbitrary
/// `EdgeInsets`/`SizedBox` values so spacing stays visually consistent
/// across every screen.
class UmojaSpacing {
  const UmojaSpacing._();

  static const xs = 4.0;
  static const sm = 8.0;
  static const md = 12.0;
  static const lg = 16.0;
  static const xl = 20.0;
  static const xxl = 24.0;
  static const xxxl = 32.0;
  static const huge = 40.0;
  static const massive = 48.0;
}
